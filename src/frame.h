/* Bevelled frame around the 3D viewport on a dark brick backdrop.
 * Uses BG tiles FRAME_BASE..FRAME_BASE+10 (244..254). Data: scratch gen_tiles.py. */
#ifndef FRAME_H
#define FRAME_H

#include <gb/gb.h>
#include <stdint.h>

#define FRAME_BASE  244u
#define FR_BRICK    (FRAME_BASE + 0u)
#define FR_TOP      (FRAME_BASE + 1u)
#define FR_TOP_R    (FRAME_BASE + 2u)   /* with rivet */
#define FR_BOT      (FRAME_BASE + 3u)
#define FR_BOT_R    (FRAME_BASE + 4u)
#define FR_LEFT     (FRAME_BASE + 5u)
#define FR_RIGHT    (FRAME_BASE + 6u)
#define FR_TL       (FRAME_BASE + 7u)
#define FR_TR       (FRAME_BASE + 8u)
#define FR_BL       (FRAME_BASE + 9u)
#define FR_BR       (FRAME_BASE + 10u)

static const uint8_t frame_tiles[11u * 16u] = {
    0x00u,0xFFu,0x7Fu,0xFFu,0x7Fu,0xFFu,0x7Fu,0xFFu,0x00u,0xFFu,0xF7u,0xFFu,0xF7u,0xFFu,0xF7u,0xFFu, /* brick */
    0xFFu,0xFFu,0xFFu,0x00u,0x00u,0xFFu,0x00u,0xFFu,0x00u,0xFFu,0x00u,0xFFu,0x00u,0xFFu,0xFFu,0xFFu, /* top */
    0xFFu,0xFFu,0xFFu,0x00u,0x00u,0xFFu,0x10u,0xEFu,0x08u,0xFFu,0x00u,0xFFu,0x00u,0xFFu,0xFFu,0xFFu, /* top+rivet */
    0xFFu,0xFFu,0xFFu,0x00u,0x00u,0xFFu,0x00u,0xFFu,0x00u,0xFFu,0x00u,0xFFu,0xFFu,0xFFu,0xFFu,0xFFu, /* bottom */
    0xFFu,0xFFu,0xFFu,0x00u,0x00u,0xFFu,0x10u,0xEFu,0x08u,0xFFu,0x00u,0xFFu,0xFFu,0xFFu,0xFFu,0xFFu, /* bottom+rivet */
    0xC1u,0xBFu,0xC1u,0xBFu,0xC1u,0xBFu,0xC1u,0xBFu,0xC1u,0xBFu,0xC1u,0xBFu,0xC1u,0xBFu,0xC1u,0xBFu, /* left */
    0xC3u,0xBFu,0xC3u,0xBFu,0xC3u,0xBFu,0xC3u,0xBFu,0xC3u,0xBFu,0xC3u,0xBFu,0xC3u,0xBFu,0xC3u,0xBFu, /* right */
    0xFFu,0xFFu,0xFFu,0x80u,0xC0u,0xBFu,0xD0u,0xAFu,0xC8u,0xBFu,0xC0u,0xBFu,0xC0u,0xBFu,0xC1u,0xBFu, /* TL */
    0xFFu,0xFFu,0xFFu,0x01u,0x03u,0xFFu,0x13u,0xEFu,0x0Bu,0xFFu,0x03u,0xFFu,0x03u,0xFFu,0xC3u,0xBFu, /* TR */
    0xC1u,0xBFu,0xC3u,0xBCu,0xC0u,0xBFu,0xD0u,0xAFu,0xC8u,0xBFu,0xC0u,0xBFu,0xFFu,0xFFu,0xFFu,0xFFu, /* BL */
    0xC3u,0xBFu,0xC3u,0x3Fu,0x03u,0xFFu,0x13u,0xEFu,0x0Bu,0xFFu,0x03u,0xFFu,0xFFu,0xFFu,0xFFu,0xFFu, /* BR */
};

static void frame_init(void)
{
    set_bkg_data(FRAME_BASE, 11u, frame_tiles);
}

/* Writes border cells only (rows 0..15); viewport cols 2..17 rows 4..11 untouched. */
static void frame_draw(void)
{
    uint8_t row[20];
    uint8_t c, y;

    for (c = 0u; c < 20u; c++) row[c] = FR_BRICK;
    for (y = 0u; y < 3u; y++) set_bkg_tiles(0u, y, 20u, 1u, row);
    for (y = 13u; y < 16u; y++) set_bkg_tiles(0u, y, 20u, 1u, row);

    /* sides: brick + left edge, right edge + brick */
    row[1] = FR_LEFT;
    for (y = 4u; y < 12u; y++) set_bkg_tiles(0u, y, 2u, 1u, row);
    row[1] = FR_BRICK;
    row[18] = FR_RIGHT;
    for (y = 4u; y < 12u; y++) set_bkg_tiles(18u, y, 2u, 1u, &row[18]);

    /* top edge, rivets at cols 6 and 13 */
    for (c = 2u; c < 18u; c++) row[c] = FR_TOP;
    row[6] = FR_TOP_R; row[13] = FR_TOP_R;
    row[1] = FR_TL; row[18] = FR_TR;
    set_bkg_tiles(0u, 3u, 20u, 1u, row);

    for (c = 2u; c < 18u; c++) row[c] = FR_BOT;
    row[6] = FR_BOT_R; row[13] = FR_BOT_R;
    row[1] = FR_BL; row[18] = FR_BR;
    set_bkg_tiles(0u, 12u, 20u, 1u, row);
}

#endif
