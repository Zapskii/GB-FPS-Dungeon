#!/usr/bin/env python3
"""Generate src/rtabs.s: the ray caster's page-aligned ROM tables.

  python3 tools/gen_rtabs.py > src/rtabs.s

Absolute area at 0x7800 (the Makefile checks that no other ROM area reaches
it), so render.s can index with H = page, L = index and no 16-bit adds:
  0x7800 al_lo[512], 0x7A00 al_hi[512]  antilog[max(i, 16) - 16], i = the
         9-bit sum log8[f] + lrc[a] (the clamp below 1/256 cell is baked in)
  0x7C00 lrc[128]    31*log2(rcp[a] / 256) + 16
  0x7C80 rcp_lo[128], 0x7D80 rcp_hi[128]  one-cell DDA step for a ray
         component a, dir scale 127*178/256 = 88.30 (main.c setup_rays)
"""
import math

DIR = 127 * 178 / 256
rcp = [32767] + [min(32767, round(256 * DIR / a)) for a in range(1, 128)]
lrc = [max(0, min(255, round(31 * math.log2(r / 256) + 16))) for r in rcp]
antilog = [min(65535, round(2 ** (i / 31))) for i in range(512)]
al = [antilog[max(i, 16) - 16] for i in range(512)]


def rows(name, vals):
    out = ['_%s::' % name]
    for i in range(0, len(vals), 16):
        out.append('        .db     ' + ', '.join(str(v) for v in vals[i:i + 16]))
    return out


lines = [
    '; ---- generated by tools/gen_rtabs.py (python3 tools/gen_rtabs.py > src/rtabs.s) ----',
    '; Page-aligned ray tables (see the script for the layout).',
    '        .module rtabs',
    '        .area   _RTABS (ABS)',
    '        .org    0x7800',
]
lines += rows('al_lo', [v & 0xFF for v in al])
lines += rows('al_hi', [v >> 8 for v in al])
lines += rows('lrc', lrc)
lines += rows('rcp_lo', [v & 0xFF for v in rcp])
lines += ['        .ds     128']
lines += rows('rcp_hi', [v >> 8 for v in rcp])
print('\n'.join(lines))
