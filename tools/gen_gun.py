# Generates src/gun.h + gun_preview.png. '.'=transparent 1=light 2=dark 3=black W=white (flash, OBP1)
import sys, zlib, struct, os
OUT_H = sys.argv[1] if len(sys.argv) > 1 else "src/gun.h"
OUT_PNG = sys.argv[2] if len(sys.argv) > 2 else "gun_preview.png"

BODY = [  # 24 x 24, pistol from behind + two hands
"..........3333..........",
".........311113.........",
".........312213.........",
"........33333333........",
".......3111111113.......",
".......3122332213.......",
".......3111111113.......",
".......3121212123.......",
".......3212121223.......",
"......333333333333......",
".....31111322311113.....",
"....3111111332111113....",
"...311111111311111113...",
"...312111111311111213...",
"..31112111113111121113..",
"..31111222113112211113..",
"..31111111113111111113..",
"..32111111132311111123..",
"..32211111132311111223..",
".3222211113222311112223.",
".322222223.33.322222223.",
".32222223..33..32222223.",
"3222222223.33.3222222223",
"322222223..33..322222223",
]
FLASH = [  # 24 x 8, over the barrel tip in the recoil frame
"..........1..1..........",
"........1.1WW1.1........",
".........1WWWW1.........",
"........1WWWWWW1........",
".........1WWWW1.........",
"........1.1WW1.1........",
"..........1..1..........",
"........................",
]
W, H = 24, 32
assert all(len(r) == W for r in BODY + FLASH), [len(r) for r in BODY + FLASH]

def canvas(top):
    c = [["."] * W for _ in range(H)]
    for y in range(H):
        src = min(y - top, len(BODY) - 1)   # repeat last row: arm runs off the bottom
        if src >= 0:
            c[y] = list(BODY[src])
    return c

IDLE_TOP, KICK = 8, 3
idle = canvas(IDLE_TOP)
fire = canvas(IDLE_TOP - KICK)
for y, row in enumerate(FLASH):
    for x, ch in enumerate(row):
        if ch != ".":
            fire[y][x] = ch

def sprites(cv):
    """6 sprites (2 rows x 3 cols of 8x16) -> (tile bytes, uses OBP1)."""
    out = []
    for sr in range(2):
        for sc in range(3):
            px = [cv[sr * 16 + y][sc * 8:sc * 8 + 8] for y in range(16)]
            obp1 = any("W" in r for r in px)
            data = []
            for r in px:
                lo = hi = 0
                for i, ch in enumerate(r):
                    v = {".": 0, "1": 1, "2": 2, "3": 3, "W": 3}[ch]
                    if obp1 and ch == "3":
                        v = 2               # OBP1 has no black: outline -> dark
                    lo |= (v & 1) << (7 - i)
                    hi |= (v >> 1) << (7 - i)
                data += [lo, hi]
            if not obp1:
                assert not any("W" in r for r in px)
            out.append((data, obp1))
    return out

si, sf = sprites(idle), sprites(fire)
assert not any(p for _, p in si)

# ---------- gun.h ----------
def art_comment(cv):
    return "\n".join(" *   " + "".join(r) for r in cv)
tiles = []
for d, _ in si + sf:
    tiles.append(d)
body_lines = []
for n, d in enumerate(tiles):
    body_lines.append("    /* %3d */ " % (130 + 2 * n) + ",".join("0x%02X" % b for b in d) + ",")
props_f = ",".join("S_PALETTE" if p else "0u" for _, p in sf)

h = f"""/* First-person pistol: 6 OBJ in 8x16 mode (3 cols x 2 rows = 24x32 px,
 * <= 3 sprites per scanline). Tiles 130..141 idle, 142..153 recoil.
 * Generated by gen_gun.py ('.' clear, 1 light, 2 dark, 3 black, W white
 * via OBP1 on the flash sprite). Idle / recoil:
{art_comment(idle)}
 *
{art_comment(fire)}
 */
#ifndef GUN_H
#define GUN_H

#include <gb/gb.h>
#include <stdint.h>

#define GUN_SPRITES 6u
#define GUN_T0      130u
#define GUN_X       80u                 /* OAM x of left column: screen 72 */
#define GUN_Y       80u                 /* OAM y of top row: screen 64, bottom 96 */

static const uint8_t gun_tiles[] = {{
{chr(10).join(body_lines)}
}};

static const uint8_t gun_dx[6] = {{ 0u, 8u, 16u, 0u, 8u, 16u }};
static const uint8_t gun_dy[6] = {{ 0u, 0u, 0u, 16u, 16u, 16u }};
static const uint8_t gun_pf[6] = {{ {props_f} }};   /* recoil props */
/* walk bob: x sways +-2, y rises 0..2 (bottom never dips into the border) */
static const uint8_t gun_bx[8] = {{ 0u, 1u, 2u, 1u, 0u, 255u, 254u, 255u }};
static const uint8_t gun_by[8] = {{ 0u, 1u, 2u, 1u, 0u, 1u, 2u, 1u }};

static void gun_init(void)
{{
    set_sprite_data(GUN_T0, 24u, gun_tiles);
}}

/* firing: recoil frame; bob: walk phase 0..255 (0 = at rest) */
static void gun_draw(uint8_t slot, uint8_t firing, uint8_t bob)
{{
    uint8_t i, x, y, t, b, s;

    b = (uint8_t)(bob >> 5);
    x = (uint8_t)(GUN_X + gun_bx[b]);
    y = (uint8_t)(GUN_Y - gun_by[b]);
    t = GUN_T0;
    if (firing) t = (uint8_t)(GUN_T0 + 12u);
    for (i = 0u; i < GUN_SPRITES; i++) {{
        s = (uint8_t)(slot + i);
        set_sprite_tile(s, (uint8_t)(t + (i << 1)));
        if (firing) set_sprite_prop(s, gun_pf[i]);
        else        set_sprite_prop(s, 0u);
        move_sprite(s, (uint8_t)(x + gun_dx[i]), (uint8_t)(y + gun_dy[i]));
    }}
}}

#endif
"""
open(OUT_H, "w").write(h)

# ---------- preview PNG: both frames over dark dither, black border below, 4x ----------
SH = [(255, 255, 255), (170, 170, 170), (85, 85, 85), (0, 0, 0)]
PW, PH, S = 40, 44, 4      # per panel: 36 px of view, 8 px border
def panel(cv):
    img = [[SH[3] if y >= 36 else SH[2 + ((x + y) & 1)] for x in range(PW)] for y in range(PH)]
    ox, oy = 8, 36 - H
    for y in range(H):
        for x in range(W):
            ch = cv[y][x]
            if ch != ".":
                img[oy + y][ox + x] = SH[{"1": 1, "2": 2, "3": 3, "W": 0}[ch]]
    return img
# recoil flash sprite uses OBP1: its '3' pixels show dark, emulate that
fire_view = [r[:] for r in fire]
for sc in range(3):
    if sf[sc][1]:
        for y in range(16):
            for x in range(sc * 8, sc * 8 + 8):
                if fire_view[y][x] == "3":
                    fire_view[y][x] = "2"
a, b2 = panel(idle), panel(fire_view)
rows = [a[y] + [SH[0]] * 4 + b2[y] for y in range(PH)]
w = len(rows[0])
raw = b"".join(b"\0" + b"".join(bytes(p) * S for p in r) for r in rows for _ in range(S))
def chunk(t, d):
    return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w * S, PH * S, 8, 2, 0, 0, 0)) \
      + chunk(b"IDAT", zlib.compress(raw)) + chunk(b"IEND", b"")
open(OUT_PNG, "wb").write(png)
print("ok", len(tiles), "tiles")
